export const getRoomBySlug = (slug) => {
  return rooms.find((room) => room.slug === slug);
};

export const getRoomsByType = (type) => {
  return rooms.filter((room) => room.type === type);
};

export const getRoomsByView = (view) => {
  return rooms.filter((room) => room.view === view);
};

export const filterRooms = (filters) => {
  return rooms.filter((room) => {
    if (filters.type && room.type !== filters.type) return false;
    if (filters.view && room.view !== filters.view) return false;
    if (filters.minPrice && room.price < filters.minPrice) return false;
    if (filters.maxPrice && room.price > filters.maxPrice) return false;
    return true;
  });
};


